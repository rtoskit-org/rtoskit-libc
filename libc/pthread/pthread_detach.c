#include <errno.h>
#include <pthread.h>
#include <rtos/rtos-port.h>

/* POSIX pthread_detach: EINVAL for a thread already detached */
int pthread_detach(pthread_t thread)
{
	return __rtos_thread_detach(thread) < 0 ? EINVAL : 0;
}
